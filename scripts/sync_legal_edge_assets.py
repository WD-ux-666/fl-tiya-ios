#!/usr/bin/env python3
"""Package the generated legal PDFs and app privacy text for Supabase deployment."""
import base64
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
edge = root / "supabase" / "functions" / "privacy-policy"
documents = {}
for key, resource, filename in (
    ("privacy_policy", "PrivacyPolicy.json", "privacy-policy.pdf"),
    ("user_agreement", "UserAgreement.json", "user-agreement.pdf"),
):
    source = (root / "FLTiya" / "Resources" / resource).read_bytes()
    document = json.loads(source)
    pdf = (root / "supabase" / "legal" / filename).read_bytes()
    if not pdf.startswith(b"%PDF-") or len(pdf) > 1024 * 1024:
        raise ValueError(f"Invalid legal PDF: {filename}")
    documents[key] = {
        "version": document["document_version"],
        "base64": base64.b64encode(pdf).decode("ascii"),
    }
    if key == "privacy_policy":
        (edge / "policy.json").write_bytes(source)
(edge / "documents.mjs").write_text(
    "// Generated by scripts/sync_legal_edge_assets.py.\nexport const documents = "
    + json.dumps(documents, indent=2)
    + ";\n",
    encoding="utf-8",
)
